create or replace function public.sync_living_npc()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $function$
declare a record;
begin
  if new.kind <> 'NPC' then return new; end if;
  select * into a from public.npc_agendas where entity_id=new.id;
  insert into public.npcs(id,campaign_id,name,personality_prompt,base_objective,current_objective,emotional_state,status,updated_at)
  values(new.id,new.campaign_id,new.name,
    coalesce(new.state->>'personality','Observant, self-directed, and consistent with established characterisation.'),
    coalesce(a.agenda,new.state->>'objective','Observe the world and protect personal interests.'),
    coalesce(a.agenda,new.state->>'objective'),
    jsonb_build_object('mood',case when coalesce(a.disposition,0)>20 then 'hopeful' when coalesce(a.disposition,0)<-20 then 'guarded' else 'neutral' end,'intensity',abs(coalesce(a.disposition,0))),
    case when new.state->>'status' in ('dead','DEAD') then 'DEAD' else 'ACTIVE' end,now())
  on conflict(id) do update set name=excluded.name,personality_prompt=excluded.personality_prompt,
    base_objective=excluded.base_objective,current_objective=excluded.current_objective,
    emotional_state=excluded.emotional_state,status=excluded.status,updated_at=now();
  return new;
end $function$;
revoke execute on function public.sync_living_npc() from public,anon,authenticated;

drop trigger if exists campaign_entities_sync_living_npc on public.campaign_entities;
create trigger campaign_entities_sync_living_npc after insert or update on public.campaign_entities
for each row execute function public.sync_living_npc();

insert into public.npcs(id,campaign_id,name,personality_prompt,base_objective,current_objective,emotional_state,status)
select e.id,e.campaign_id,e.name,
  coalesce(e.state->>'personality','Observant, self-directed, and consistent with established characterisation.'),
  coalesce(a.agenda,'Observe the world and protect personal interests.'),a.agenda,
  jsonb_build_object('mood',case when coalesce(a.disposition,0)>20 then 'hopeful' when coalesce(a.disposition,0)<-20 then 'guarded' else 'neutral' end,'intensity',abs(coalesce(a.disposition,0))),
  case when e.state->>'status' in ('dead','DEAD') then 'DEAD' else 'ACTIVE' end
from public.campaign_entities e left join public.npc_agendas a on a.entity_id=e.id
where e.kind='NPC'
on conflict(id) do update set name=excluded.name,personality_prompt=excluded.personality_prompt,
base_objective=excluded.base_objective,current_objective=excluded.current_objective,emotional_state=excluded.emotional_state,updated_at=now();

insert into public.npc_memory(campaign_id,npc_id,memory_type,content,metadata,importance,decay_weight)
select n.campaign_id,n.id,'FACT','My enduring objective is: '||n.base_objective,
jsonb_build_object('origin','living_characters_bootstrap'),0.9,1
from public.npcs n
where not exists(select 1 from public.npc_memory m where m.npc_id=n.id and m.metadata->>'origin'='living_characters_bootstrap');
