-- Living Characters: identity, durable memory, relationships and auditable actions.
create extension if not exists vector with schema extensions;

create table if not exists public.npcs (
  id uuid primary key references public.campaign_entities(id) on delete cascade,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  name text not null,
  personality_prompt text not null default 'Observant, self-directed, consistent with established characterisation.',
  base_objective text not null default 'Observe the world and protect personal interests.',
  current_objective text,
  emotional_state jsonb not null default '{"mood":"neutral","intensity":0}'::jsonb,
  status text not null default 'ACTIVE' check (status in ('ACTIVE','INCAPACITATED','MISSING','DEAD','DEPARTED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(campaign_id,id)
);

create table if not exists public.npc_memory (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  npc_id uuid not null references public.npcs(id) on delete cascade,
  memory_type text not null check (memory_type in ('FACT','RELATIONSHIP','EVENT','PROMISE','SUSPICION','GOAL')),
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  embedding extensions.vector(1536),
  importance real not null default 0.5 check (importance between 0 and 1),
  decay_weight real not null default 1 check (decay_weight between 0 and 1),
  occurred_at timestamptz not null default now(),
  last_recalled_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.npc_relationships (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  npc_id uuid not null references public.npcs(id) on delete cascade,
  target_type text not null check (target_type in ('PLAYER','NPC')),
  target_id uuid not null,
  score smallint not null default 0 check (score between -100 and 100),
  trust smallint not null default 0 check (trust between -100 and 100),
  fear smallint not null default 0 check (fear between 0 and 100),
  respect smallint not null default 0 check (respect between -100 and 100),
  last_updated timestamptz not null default now(),
  unique(campaign_id,npc_id,target_type,target_id)
);

create table if not exists public.npc_action_log (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  npc_id uuid not null references public.npcs(id) on delete cascade,
  tick_id bigint not null,
  proposed_action jsonb not null,
  validation_status text not null default 'PENDING' check (validation_status in ('PENDING','APPROVED','REJECTED','MODIFIED')),
  validation_reason text,
  outcome jsonb,
  created_at timestamptz not null default now(),
  unique(campaign_id,npc_id,tick_id)
);

create index if not exists npcs_campaign_idx on public.npcs(campaign_id,status);
create index if not exists npc_memory_lookup_idx on public.npc_memory(campaign_id,npc_id,memory_type,created_at desc);
create index if not exists npc_memory_embedding_idx on public.npc_memory using hnsw (embedding vector_cosine_ops) where embedding is not null;
create index if not exists npc_relationships_lookup_idx on public.npc_relationships(campaign_id,npc_id,score desc);
create index if not exists npc_action_log_tick_idx on public.npc_action_log(campaign_id,tick_id desc,npc_id);

alter table public.npcs enable row level security;
